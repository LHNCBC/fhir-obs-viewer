const fs = require('fs');
const path = require('path');
const {
  buildDefinitionsIndex
} = require('../src/app/shared/definitions/webpack-loader.js');

const repoRoot = path.resolve(__dirname, '..');
const definitionsFolder = path.join(repoRoot, 'src/app/shared/definitions');
const definitionsIndexPath = path.join(definitionsFolder, 'index.json');
const definitionsOptionsPath = path.join(definitionsFolder, 'webpack-options.json');
const generatedDefinitionsPath = path.join(
  definitionsFolder,
  'generated-index.json'
);
const packageJsonPath = path.join(repoRoot, 'package.json');
const appVersionPath = path.join(repoRoot, 'src/app/shared/app-version.ts');

function syncGeneratedDefinitions() {
  const definitionsIndex = JSON.parse(
    fs.readFileSync(definitionsIndexPath, 'utf8')
  );
  const webpackOptions = JSON.parse(
    fs.readFileSync(definitionsOptionsPath, 'utf8')
  );
  const generatedIndex = buildDefinitionsIndex(
    definitionsIndex,
    webpackOptions,
    definitionsFolder
  );
  fs.writeFileSync(
    generatedDefinitionsPath,
    JSON.stringify(generatedIndex, null, 2) + '\n'
  );
}

function syncAppVersion() {
  const { version } = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
  fs.writeFileSync(
    appVersionPath,
    '// Auto-generated by bin/sync-generated-assets.js\n' +
      `export const APP_VERSION = '${version}' as const;\n`
  );

  return version;
}

function syncGeneratedAssets() {
  syncGeneratedDefinitions();
  const appVersion = syncAppVersion();

  return {
    generatedDefinitionsPath,
    appVersionPath,
    appVersion
  };
}

if (require.main === module) {
  try {
    const { appVersion } = syncGeneratedAssets();
    console.log(`Synced generated definitions and app version ${appVersion}.`);
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}

module.exports = {
  syncGeneratedAssets,
  syncGeneratedDefinitions,
  syncAppVersion
};

